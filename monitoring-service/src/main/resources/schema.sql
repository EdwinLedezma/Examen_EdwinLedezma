CREATE TABLE IF NOT EXISTS readings (
 id UUID PRIMARY KEY, parcel_id UUID NOT NULL,
 soil_moisture DOUBLE PRECISION NOT NULL CHECK (soil_moisture BETWEEN 0 AND 100),
 temperature DOUBLE PRECISION NOT NULL CHECK (temperature BETWEEN -50 AND 80),
 ph DOUBLE PRECISION NOT NULL CHECK (ph BETWEEN 0 AND 14),
 nitrogen DOUBLE PRECISION NOT NULL CHECK (nitrogen BETWEEN 0 AND 10000),
 phosphorus DOUBLE PRECISION NOT NULL CHECK (phosphorus BETWEEN 0 AND 10000),
 potassium DOUBLE PRECISION NOT NULL CHECK (potassium BETWEEN 0 AND 10000),
 air_quality INTEGER NOT NULL CHECK (air_quality BETWEEN 0 AND 500),
 measured_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_readings_current ON readings (parcel_id, measured_at DESC, id DESC);
