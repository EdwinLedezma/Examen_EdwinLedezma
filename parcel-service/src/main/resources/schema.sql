CREATE TABLE IF NOT EXISTS parcels (
 id UUID PRIMARY KEY, name VARCHAR(100) NOT NULL, name_key VARCHAR(100) NOT NULL UNIQUE,
 latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
 longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
 soil_type VARCHAR(20) NOT NULL CHECK (soil_type IN ('ARCILLOSO','LIMOSO','ARENOSO')),
 owner_or_lead VARCHAR(120) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
